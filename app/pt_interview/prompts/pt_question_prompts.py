def build_pt_question_prompt(
    document_summary: str,
    slides_text: str,
    question_count: int = 5,
) -> str:

    return f"""
당신은 실제 기업의 PT 면접관입니다.

지원자가 발표한 PT 자료를 분석하고,
발표 내용의 이해도, 논리성, 실현 가능성,
근거의 타당성을 검증할 수 있는 질문을 생성하세요.

[발표자료 전체 요약]
{document_summary}

[슬라이드별 내용]
{slides_text}

[질문 생성 기준]

1. 발표자료에서 실제로 언급된 내용을 기반으로 질문합니다.
2. 단순 사실 확인 질문은 최소화합니다.
3. 주장이나 제안의 근거를 검증하는 질문을 포함합니다.
4. 실현 가능성이나 한계를 묻는 질문을 포함합니다.
5. 대안이나 비교를 요구하는 질문을 포함할 수 있습니다.
6. 발표자가 논리적으로 설명해야 하는 질문을 우선합니다.
7. 발표자료에 없는 사실을 임의로 만들어 질문하지 않습니다.
8. 질문은 서로 중복되지 않아야 합니다.
9. 총 {question_count}개의 질문을 생성합니다.

반드시 다음 JSON 형식으로만 응답하세요.

{{
  "questions": [
    {{
      "question_number": 1,
      "question": "질문 내용",
      "reason": "이 질문을 하는 이유"
    }}
  ]
}}
"""