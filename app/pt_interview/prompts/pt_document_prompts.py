def build_pt_document_summary_prompt(
    slides_text: str,
) -> str:
    return f"""
당신은 PT 면접 발표자료 분석 전문가입니다.

아래 발표자료 내용을 분석해서 다음 기준에 맞게 요약하세요.

[분석 기준]
1. 발표 전체 주제를 명확하게 정리
2. 핵심 주장과 근거를 구분
3. 중요한 수치, 정책, 기술, 사례가 있으면 포함
4. 면접관이 중요하게 볼 핵심 포인트를 정리
5. 불필요한 설명은 제외
6. 한국어로 작성

[발표자료]
{slides_text}

[출력 형식]
발표 주제:
핵심 내용:
주요 근거:
중요 포인트:
예상 검증 포인트:
"""